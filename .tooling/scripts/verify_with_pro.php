<?php

/*
 * Verify every policy against every sample with a matching config_format, using rConfig Pro's
 * real parser and evaluator, and compare the results with .tooling/expected/{name}.yaml.
 *
 * Usage:
 *   RCONFIG_PRO_PATH=../rconfig8 php .tooling/scripts/verify_with_pro.php            compare, exit 1 on any difference
 *   RCONFIG_PRO_PATH=../rconfig8 php .tooling/scripts/verify_with_pro.php --update   rewrite .tooling/expected/*.yaml from current results
 *   RCONFIG_PRO_PATH=../rconfig8 php .tooling/scripts/verify_with_pro.php --uniform  also list rules with the same result on every sample
 *
 * Policies in dot-folders (.drafts, .tooling) are skipped. RCONFIG_PRO_PATH defaults to ../rconfig8
 * relative to this repository. Pro is used read-only:
 * activity logging is switched off and the database connection is pointed at in-memory SQLite
 * for this process only, so nothing is written to Pro's database or files.
 */

$repo = dirname(__DIR__, 2);
$pro = getenv('RCONFIG_PRO_PATH') ?: $repo . '/../rconfig8';
$pro = realpath($pro) ?: $pro;
$update = in_array('--update', $argv, true);
$uniform = in_array('--uniform', $argv, true);

if (! is_file($pro . '/vendor/autoload.php') || ! is_file($pro . '/bootstrap/app.php')) {
    fwrite(STDERR, "rConfig Pro not found at {$pro}. Set RCONFIG_PRO_PATH.\n");
    exit(2);
}

require $pro . '/vendor/autoload.php';
$app = require $pro . '/bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();
config([
    'activitylog.enabled' => false,
    'database.default' => 'sqlite',
    'database.connections.sqlite.database' => ':memory:',
]);

use App\Services\Compliance\Definitions\PolicyDefinitionEvaluator;
use App\Services\Compliance\Definitions\PolicyDefinitionParser;
use Symfony\Component\Yaml\Yaml;

$proCommit = trim((string) shell_exec('git -C ' . escapeshellarg($pro) . ' rev-parse --short=10 HEAD 2>/dev/null')) ?: 'unknown';

// Samples, grouped by config_format.
$samples = [];
foreach (glob($repo . '/.tooling/samples/*/samples.yaml') as $index) {
    $vendor = basename(dirname($index));
    foreach (Yaml::parseFile($index)['samples'] ?? [] as $entry) {
        $samples[$entry['config_format']][] = [
            'key' => $vendor . '/' . $entry['file'],
            'path' => dirname($index) . '/' . $entry['file'],
        ];
    }
}

$policies = [];
$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($repo, FilesystemIterator::SKIP_DOTS));
foreach ($it as $file) {
    $path = $file->getPathname();
    $rel = substr($path, strlen($repo) + 1);
    if (str_ends_with($path, '.policy') && ! str_starts_with($rel, '.')) {
        $policies[] = $rel;
    }
}
sort($policies);

$differences = 0;
$uniformRules = [];

foreach ($policies as $rel) {
    $name = basename($rel, '.policy');
    $metaPath = $repo . '/' . substr($rel, 0, -strlen('.policy')) . '.meta.yaml';
    if (! is_file($metaPath)) {
        echo "DIFF {$rel}: no metadata file\n";
        $differences++;

        continue;
    }
    $format = Yaml::parseFile($metaPath)['config_format'] ?? null;
    $matching = $samples[$format] ?? [];
    if ($matching === []) {
        echo "DIFF {$rel}: no samples with config_format {$format}\n";
        $differences++;

        continue;
    }

    $parsed = array_values((new PolicyDefinitionParser)->parse($repo . '/' . $rel));
    $actual = [];
    foreach ($parsed as $i => $rule) {
        $actual[$i] = [
            'rule' => $i + 1,
            'description' => $rule['comment'],
            'method' => $rule['policyMethod'],
            'results' => [],
        ];
    }
    foreach ($matching as $sample) {
        $evaluated = (new PolicyDefinitionEvaluator)->evaluate($parsed, (object) ['config_location' => $sample['path'], 'id' => 0]);
        foreach ($parsed as $i => $_) {
            $actual[$i]['results'][$sample['key']] = $evaluated[$i]['result'];
        }
    }

    foreach ($actual as $rule) {
        $values = array_unique(array_values($rule['results']));
        if (count($values) === 1) {
            $uniformRules[] = sprintf('%s rule %d (%s): %s on all %d samples', $rel, $rule['rule'], $rule['description'], $values[0], count($rule['results']));
        }
    }

    $expectedPath = $repo . '/.tooling/expected/' . $name . '.yaml';
    if ($update) {
        $header = "# Expected results for {$rel}, one entry per rule, per sample.\n"
            . "# Generated by .tooling/scripts/verify_with_pro.php --update against rConfig Pro {$proCommit}.\n"
            . "# Review every change before committing it.\n";
        @mkdir(dirname($expectedPath), 0777, true);
        file_put_contents($expectedPath, $header . Yaml::dump(['policy' => $rel, 'rules' => $actual], 4, 2));
        echo "wrote .tooling/expected/{$name}.yaml (" . count($actual) . ' rules x ' . count($matching) . " samples)\n";

        continue;
    }

    if (! is_file($expectedPath)) {
        echo "DIFF {$rel}: no .tooling/expected/{$name}.yaml\n";
        $differences++;

        continue;
    }
    $expected = Yaml::parseFile($expectedPath)['rules'] ?? [];
    if (count($expected) !== count($actual)) {
        echo "DIFF {$rel}: expected " . count($expected) . ' rules, Pro parsed ' . count($actual) . "\n";
        $differences++;
    }
    foreach ($actual as $i => $rule) {
        $want = $expected[$i] ?? null;
        if ($want === null) {
            continue;
        }
        if (($want['description'] ?? null) !== $rule['description']) {
            echo "DIFF {$rel} rule {$rule['rule']}: description changed from \"{$want['description']}\" to \"{$rule['description']}\"\n";
            $differences++;
        }
        $keys = array_unique(array_merge(array_keys($want['results'] ?? []), array_keys($rule['results'])));
        sort($keys);
        foreach ($keys as $sample) {
            $was = $want['results'][$sample] ?? 'absent';
            $now = $rule['results'][$sample] ?? 'absent';
            if ($was !== $now) {
                echo "DIFF {$rel} rule {$rule['rule']} ({$rule['description']}) on {$sample}: expected {$was}, got {$now}\n";
                $differences++;
            }
        }
    }
}

if ($uniform) {
    echo "\nRules with the same result on every sample (untested or broken):\n";
    foreach ($uniformRules as $line) {
        echo "  {$line}\n";
    }
}

if ($update) {
    echo "\nExpected results written for " . count($policies) . " policies against Pro {$proCommit}. Review them before committing.\n";
    exit(0);
}

echo "\n" . count($policies) . " policies checked against Pro {$proCommit}: {$differences} differences\n";
exit($differences > 0 ? 1 : 0);
