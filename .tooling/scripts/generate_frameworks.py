#!/usr/bin/env python3
"""Generate framework policy files from the hardening topic files.

Usage: python3 .tooling/scripts/generate_frameworks.py [--check] [--root DIR]

For each vendor and framework, collects every rule in that vendor's hardening topic files whose
.meta.yaml lists a reference for the framework, and writes {vendor}/{os}-{framework}.policy and its
.meta.yaml. Rule bodies are copied from the topic file unchanged; each description is prefixed with
the rule's control reference. A framework with no tagged rules gets no file.

The topic files are the only source of rules. Never edit a generated file: edit the topic file and
run this script. --check writes nothing and exits 1 when a generated file is missing, differs from
what this script would write, or is no longer produced. The lint runs the same check.

Exit status is 1 on any problem, 0 otherwise.
Dependencies: Python 3.9+ standard library and PyYAML.
"""
import argparse
import glob
import json
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

# Vendor folders covered, with the OS name used in file names and titles.
VENDORS = {
    'cisco': ('ios', 'Cisco IOS'),
    'fortinet': ('fortios', 'FortiOS'),
    'juniper': ('junos', 'Junos'),
}

# (file suffix, references key, description prefix, framework name, identifier scheme)
FRAMEWORKS = (
    ('nist-800-53', 'nist_800_53', 'NIST', 'NIST SP 800-53', 'NIST SP 800-53 control identifiers, as published'),
    ('nist-csf', 'nist_csf', 'NIST CSF', 'NIST Cybersecurity Framework 1.1', 'NIST CSF 1.1 subcategory identifiers, as published'),
    ('hipaa', 'hipaa', 'HIPAA', 'HIPAA Security Rule, 45 CFR 164.312', '45 CFR section numbers, as published'),
    ('iso27001', 'iso27001', 'ISO 27001', 'ISO/IEC 27001:2022 Annex A', 'ISO/IEC 27001:2022 Annex A control numbers, as published'),
)

# A framework file is only as tested as its least tested source.
STATUS_ORDER = ('lab-tested', 'synthetic-tested', 'under-review')

HEADER = (
    '# Generated by .tooling/scripts/generate_frameworks.py from the topic files under sources.\n'
    '# Do not edit this file or its .policy file: edit the topic files, then run the generator.\n'
)


class GeneratorError(Exception):
    pass


def load_methods():
    with open(os.path.join(HERE, 'methods.json'), encoding='utf-8') as fh:
        return json.load(fh)


def version_tuple(v):
    return tuple(int(x) for x in str(v).split('.'))


def natural_key(control):
    """Sort AC-2 before AC-17 and 164.312(a)(1) before 164.312(b)."""
    return [int(p) if p.isdigit() else p for p in re.findall(r'\d+|\D+', control)]


def quote(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def split_rules(text):
    """Split a policy file into (description, lines from the #[ directive to the end of the body)."""
    rules = []
    for line in text.split('\n'):
        if line.startswith('//'):
            rules.append([line[2:].strip(), []])
        elif rules:
            rules[-1][1].append(line)
    for rule in rules:
        while rule[1] and rule[1][-1].strip() == '':
            rule[1].pop()
    return [(d, body) for d, body in rules]


def topic_files(root, vendor):
    """The vendor's hardening topic files, as (relative policy path, metadata), in file name order."""
    topics = []
    for meta_path in sorted(glob.glob(os.path.join(root, vendor, '*.meta.yaml'))):
        with open(meta_path, encoding='utf-8') as fh:
            meta = yaml.safe_load(fh) or {}
        if meta.get('kind') != 'hardening' or meta.get('generated'):
            continue
        topics.append((os.path.relpath(meta_path, root)[:-len('.meta.yaml')] + '.policy', meta))
    return topics


def collect(root, vendor):
    """Every rule of the vendor's topic files, with its source, metadata and body."""
    rules = []
    for rel, meta in topic_files(root, vendor):
        if not meta.get('rules'):
            continue  # no rules list, so no references to collect
        with open(os.path.join(root, rel), encoding='utf-8') as fh:
            parsed = split_rules(fh.read())
        listed = [r.get('description') for r in meta['rules']]
        if [d for d, _ in parsed] != listed:
            raise GeneratorError(f'{rel}: rule descriptions do not match the rules list in its .meta.yaml')
        for index, ((description, body), entry) in enumerate(zip(parsed, meta['rules'])):
            rules.append({'source': rel, 'index': index, 'description': description, 'body': body,
                          'references': entry.get('references') or {}, 'meta': meta})
    return rules


def render(vendor, framework, rules, methods):
    """Return (policy text, metadata text) for one framework file, or None when no rule is tagged."""
    os_name, label = VENDORS[vendor]
    suffix, key, prefix, name, ids = framework
    tagged = [r for r in rules if r['references'].get(key)]
    if not tagged:
        return None
    tagged.sort(key=lambda r: (natural_key(sorted(r['references'][key], key=natural_key)[0]), r['source'], r['index']))

    sources = sorted({r['source'] for r in tagged})
    metas = {r['source']: r['meta'] for r in tagged}
    for field in ('config_format', 'collection_command'):
        values = {m.get(field) for m in metas.values()}
        if len(values) != 1:
            raise GeneratorError(f'{vendor} {suffix}: source topic files disagree on {field}')
    first = metas[sources[0]]

    used = set()
    blocks, entries = [], []
    for r in tagged:
        controls = sorted(r['references'][key], key=natural_key)
        description = f"{prefix} {', '.join(controls)}: {r['description']}"
        directive = re.fullmatch(r'#\[(\w+)\]', r['body'][0] if r['body'] else '')
        if not directive:
            raise GeneratorError(f"{r['source']}: rule {r['index'] + 1} has no #[method] line")
        used.add(directive.group(1))
        blocks.append('\n'.join([f'// {description}'] + r['body']))
        entries.append((description, r))
    policy = '\n\n'.join(blocks) + '\n'

    min_version = max((methods['min_version'][m] for m in used), key=version_tuple)
    status = max((m.get('status') for m in metas.values()), key=STATUS_ORDER.index)
    notes = []
    for source in sources:
        note = metas[source].get('notes')
        if note and note not in notes:
            notes.append(note)

    lines = [HEADER.rstrip('\n'),
             f'title: {quote(f"{label} {name}")}',
             f'description: {quote(f"{label} hardening rules that list a {name} reference, collected from the topic files. They are relevant checks, not a certification or a full assessment.")}',
             f'vendor: {vendor}',
             f'os: {os_name}',
             f"config_format: {first['config_format']}",
             f"collection_command: {quote(first['collection_command'])}",
             'kind: framework',
             'generated: true',
             f'min_rconfig_version: {min_version}',
             f'status: {status}',
             'framework_claim:',
             f'  framework: {quote(name)}',
             f'  ids: {quote(ids)}',
             '  ids_local: false']
    if notes:
        lines.append(f"notes: {quote(' '.join(notes))}")
    lines.append('sources:')
    lines += [f'  - {s}' for s in sources]
    lines.append('rules:')
    for description, r in entries:
        lines.append(f'  - description: {quote(description)}')
        lines.append(f"    source: {r['source']}")
        lines.append(f"    source_rule: {quote(r['description'])}")
        lines.append('    references:')
        for ref_key, values in r['references'].items():
            lines.append(f'      {ref_key}: [' + ', '.join(quote(v) for v in values) + ']')
    return policy, '\n'.join(lines) + '\n'


def generate(root):
    """Return {relative path: text} for every framework file the topic files produce."""
    methods = load_methods()
    out = {}
    for vendor in VENDORS:
        if not os.path.isdir(os.path.join(root, vendor)):
            continue
        rules = collect(root, vendor)
        for framework in FRAMEWORKS:
            rendered = render(vendor, framework, rules, methods)
            if rendered is None:
                continue
            stem = f'{vendor}/{VENDORS[vendor][0]}-{framework[0]}'
            out[stem + '.policy'], out[stem + '.meta.yaml'] = rendered
    return out


def existing_generated(root):
    """Relative paths of the framework files already in the repository (policy and metadata)."""
    found = set()
    for vendor in VENDORS:
        for meta_path in glob.glob(os.path.join(root, vendor, '*.meta.yaml')):
            with open(meta_path, encoding='utf-8') as fh:
                meta = yaml.safe_load(fh) or {}
            if meta.get('generated') or meta.get('kind') == 'framework':
                rel = os.path.relpath(meta_path, root)
                found |= {rel, rel[:-len('.meta.yaml')] + '.policy'}
    return found


def check(root):
    """Return a list of (relative path, problem) for generated files that are missing, edited or stale."""
    try:
        wanted = generate(root)
    except GeneratorError as exc:
        return [('.tooling/scripts/generate_frameworks.py', str(exc))]
    problems = []
    for rel, text in sorted(wanted.items()):
        path = os.path.join(root, rel)
        if not os.path.exists(path):
            problems.append((rel, 'generated file is missing; run .tooling/scripts/generate_frameworks.py'))
            continue
        with open(path, encoding='utf-8', newline='') as fh:
            if fh.read() != text:
                problems.append((rel, 'differs from the generator output; edit the topic files, not this file, then run the generator'))
    for rel in sorted(existing_generated(root) - set(wanted)):
        if os.path.exists(os.path.join(root, rel)):
            problems.append((rel, 'the topic files no longer produce this generated file; delete it or run the generator'))
    return problems


def write(root):
    """Write every generated file and delete generated files that are no longer produced."""
    wanted = generate(root)
    for rel in sorted(existing_generated(root) - set(wanted)):
        path = os.path.join(root, rel)
        if os.path.exists(path):
            os.remove(path)
            print(f'removed {rel}')
    for rel, text in sorted(wanted.items()):
        with open(os.path.join(root, rel), 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(text)
        if rel.endswith('.policy'):
            rules = sum(1 for line in text.split('\n') if line.startswith('#['))
            print(f'wrote {rel} ({rules} rules)')


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='write nothing; exit 1 if any generated file is out of date')
    parser.add_argument('--root', default=REPO)
    args = parser.parse_args()
    if args.check:
        problems = check(args.root)
        for rel, msg in problems:
            print(f'{rel}: {msg}')
        print(f'generated framework files: {len(problems)} problems')
        return 1 if problems else 0
    try:
        write(args.root)
    except GeneratorError as exc:
        print(f'error: {exc}')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
